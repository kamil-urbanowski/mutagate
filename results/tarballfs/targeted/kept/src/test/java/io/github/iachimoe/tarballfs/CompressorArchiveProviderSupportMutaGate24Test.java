  @Test
  void basicViewIsAcceptedAndOtherViewsAreRejected() throws IOException {
    SingleEntryArchiveFormat format = SingleEntryArchiveFormat.GZIP;
    Path path = new SingleEntryArchivePath(new StubFileSystem(), format, true, "x");
    FileSystemProvider provider = new StubProvider();

    Map<String, Object> result =
        CompressorArchiveProviderSupport.readBasicAttributesMap(path, "basic:size", provider, format);
    assertEquals(1, result.size());
    assertEquals(5L, result.get("size"));

    Map<String, Object> noColon =
        CompressorArchiveProviderSupport.readBasicAttributesMap(path, "basic", provider, format);
    assertEquals(5L, noColon.get("size"));

    assertThrows(
        UnsupportedOperationException.class,
        () -> CompressorArchiveProviderSupport.readBasicAttributesMap(path, "posix:size", provider, format));
  }
